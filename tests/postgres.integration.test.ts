import { afterAll, beforeAll, beforeEach, describe, expect, it } from "bun:test";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DbConfigSchema } from "../src/config";
import { buildRestoreCommand, runDatabaseCommand, transferDatabase } from "../src/db/client";
import { dumpDatabase } from "../src/db/dumper";
import { executeRestore, prepareRestoreSql } from "../src/db/restorer";
import { S3Storage } from "../src/storage";
import { s3Fixture } from "./helpers/s3";

const container = process.env.OPSYNC_PG_TEST_CONTAINER ?? "";
const tag = `opsync_test_${crypto.randomUUID().replaceAll("-", "")}`;
const sourceName = `${tag}_src`;
const targetName = `${tag}_dst`;
const roleName = `${tag}_role`;
const profile = (database: string) =>
    DbConfigSchema.parse({
        dialect: "pg",
        host: "127.0.0.1",
        port: 5432,
        database,
        user: roleName,
        password: "opsync-integration-fixture-only",
    });
const source = profile(sourceName);
const target = profile(targetName);
let directory: string;
const created: string[] = [];

async function admin(sql: string) {
    const pgUserExpr = "$POSTGRES_USER";
    const proc = Bun.spawn({
        cmd: [
            "docker",
            "exec",
            "-i",
            "-u",
            "postgres",
            container,
            "sh",
            "-c",
            `exec psql -X --username="\${POSTGRES_USER:-postgres}" --dbname=postgres --set=ON_ERROR_STOP=1`.replace(
                pgUserExpr,
                pgUserExpr,
            ),
        ],
        stdin: new TextEncoder().encode(sql),
        stdout: "pipe",
        stderr: "pipe",
    });
    const [, errors, code] = await Promise.all([
        new Response(proc.stdout).text(),
        new Response(proc.stderr).text(),
        proc.exited,
    ]);
    if (code) throw new Error(`Fixture database setup failed: ${errors}`);
}

async function query(db: typeof source, sql: string): Promise<string> {
    const plan = buildRestoreCommand(db, container);
    plan.argv.push("-Atq");
    return new TextDecoder().decode(await runDatabaseCommand(plan, new TextEncoder().encode(sql))).trim();
}

let exportNumber = 0;
async function exportDatabase(
    mode: "full" | "schema" | "data",
    gzip = false,
    tables?: string[],
    ignoreTables?: string[],
) {
    return dumpDatabase({
        db: source,
        mode,
        gzip,
        tables,
        ignoreTables,
        container,
        localDir: directory,
        prefix: `fixture_${++exportNumber}_`,
    });
}
async function restoreFile(path: string) {
    const bytes = prepareRestoreSql(await Bun.file(path).bytes(), "pg");
    await executeRestore({ targetDb: target, sqlData: bytes, container });
}

describe.skipIf(!container)("PostgreSQL native round trips", () => {
    beforeAll(async () => {
        directory = await mkdtemp(join(tmpdir(), "opsync-pg-"));
        await admin(`CREATE ROLE "${roleName}" LOGIN PASSWORD 'opsync-integration-fixture-only';`);
        // These random, suite-owned databases isolate full dumps from development and managed test fixtures.
        for (const name of [sourceName, targetName]) {
            await admin(`CREATE DATABASE "${name}" OWNER "${roleName}";`);
            created.push(name);
        }
        await query(
            source,
            `
            CREATE TABLE parents (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code text NOT NULL UNIQUE,
                enabled boolean NOT NULL DEFAULT true,
                payload jsonb NOT NULL DEFAULT '{}',
                created timestamptz NOT NULL DEFAULT now()
            );
            CREATE TABLE children (
                id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                parent_id integer NOT NULL REFERENCES parents(id),
                amount integer NOT NULL CHECK (amount > 0)
            );
            CREATE VIEW enabled_parents AS SELECT id, code FROM parents WHERE enabled;
            CREATE FUNCTION parent_count() RETURNS bigint LANGUAGE sql AS $$ SELECT count(*) FROM parents $$;
            INSERT INTO parents (code, payload) VALUES ('fixture-one', '{"source":"DEFINER=fixture"}'), ('fixture-two', '{}');
            INSERT INTO children (parent_id, amount) VALUES (1, 5);
        `,
        );
    }, 15000);

    beforeEach(async () => {
        await query(target, "DROP SCHEMA public CASCADE; CREATE SCHEMA public;");
    });

    afterAll(async () => {
        for (const name of created.reverse()) await admin(`DROP DATABASE "${name}" WITH (FORCE);`);
        await admin(`DROP ROLE IF EXISTS "${roleName}";`);
        if (directory) await rm(directory, { recursive: true, force: true });
    }, 15000);

    it("restores schema, views and functions without business rows", async () => {
        const dump = await exportDatabase("schema");
        await restoreFile(dump.finalPath);
        expect(await query(target, "SELECT parent_count();")).toBe("0");
        expect(await query(target, "INSERT INTO parents (code) VALUES ('after-schema') RETURNING id;")).toBe("1");
        expect(await query(target, "SELECT code FROM enabled_parents;")).toBe("after-schema");
    });

    it("restores gzip full dumps with JSON, booleans, constraints and sequence state", async () => {
        const dump = await exportDatabase("full", true);
        await restoreFile(dump.finalPath);
        expect(await query(target, "SELECT parent_count();")).toBe("2");
        expect(await query(target, "SELECT payload->>'source' FROM parents WHERE id=1;")).toBe("DEFINER=fixture");
        expect(await query(target, "SELECT bool_and(enabled) FROM parents;")).toBe("t");
        expect(await query(target, "INSERT INTO parents (code) VALUES ('after-full') RETURNING id;")).toBe("3");
        await expect(query(target, "INSERT INTO children (parent_id, amount) VALUES (99999, 1);")).rejects.toThrow(
            "foreign key",
        );
    });

    it.skipIf(!s3Fixture)("restores a PostgreSQL gzip dump downloaded from Garage", async () => {
        if (!s3Fixture) return;
        const storage = new S3Storage(s3Fixture, `postgres/${tag}`);
        const key = "roundtrip.sql.gz";
        try {
            const dump = await exportDatabase("full", true);
            await storage.put(key, await Bun.file(dump.finalPath).bytes());
            const sqlData = prepareRestoreSql(await storage.get(key), "pg");
            await executeRestore({ targetDb: target, sqlData, container });
            expect(await query(target, "SELECT parent_count();")).toBe("2");
            expect(await query(target, "SELECT payload->>'source' FROM parents WHERE id=1;")).toBe("DEFINER=fixture");
            expect(await query(target, "SELECT sum(amount) FROM children;")).toBe("5");
            expect(await query(target, "INSERT INTO parents (code) VALUES ('after-s3') RETURNING id;")).toBe("3");
        } finally {
            await storage.delete(key);
        }
    });

    it("loads data-only dumps into an existing empty schema", async () => {
        await restoreFile((await exportDatabase("schema")).finalPath);
        await restoreFile((await exportDatabase("data")).finalPath);
        expect(await query(target, "SELECT parent_count();")).toBe("2");
        expect(await query(target, "INSERT INTO parents (code) VALUES ('after-data') RETURNING id;")).toBe("3");
    });

    it("preserves table inclusion and exclusion scope", async () => {
        const dump = await exportDatabase("full", false, ["parents", "children"], ["children"]);
        await restoreFile(dump.finalPath);
        expect(await query(target, "SELECT count(*) FROM parents;")).toBe("2");
        expect(await query(target, "SELECT to_regclass('children') IS NULL;")).toBe("t");
    });

    it("stops on the first restore error and reports the partial-restore contract", async () => {
        const sql = new TextEncoder().encode(
            "CREATE TABLE before_error(id integer); SELECT 1/0; CREATE TABLE after_error(id integer);",
        );
        await expect(executeRestore({ targetDb: target, sqlData: sql, container })).rejects.toThrow("exited with code 3");
        expect(
            await query(target, "SELECT to_regclass('before_error') IS NOT NULL AND to_regclass('after_error') IS NULL;"),
        ).toBe("t");
    });

    it("transfers selected tables between same-engine profiles", async () => {
        await transferDatabase(source, target, ["parents", "children"], container);
        expect(await query(target, "SELECT count(*) FROM parents;")).toBe("2");
        expect(await query(target, "SELECT sum(amount) FROM children;")).toBe("5");
    });

    it("reports an export failure even if an empty import could succeed", async () => {
        await expect(transferDatabase(profile(`${sourceName}_missing`), target, ["parents"], container)).rejects.toThrow(
            "pg_dump",
        );
    });

    it("reports the import failure rather than hiding it behind a terminated exporter", async () => {
        // Keep the exporter busy when the destination refuses its connection.
        await query(
            source,
            "INSERT INTO parents (code, payload) SELECT 'bulk-' || n, jsonb_build_object('payload', repeat(md5(n::text), 256)) FROM generate_series(1, 5000) n;",
        );
        await expect(transferDatabase(source, profile(`${targetName}_missing`), ["parents"], container)).rejects.toThrow(
            "psql",
        );
    });
});
